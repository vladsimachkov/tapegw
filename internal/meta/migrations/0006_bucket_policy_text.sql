-- +goose Up
-- Bucket Policy: колонка policy хранится как text, а не jsonb.
--
-- Причина не в вкусе. versitygw отдаёт документ бэкенда клиенту дословно:
-- контроллер GetBucketPolicy возвращает те самые байты, что вернул
-- Backend.GetBucketPolicy, а posix-бэкенд — эталон, с которого мы берём
-- поведение, — пишет тело запроса в файл как есть. jsonb же пересобирает JSON:
-- сортирует ключи, схлопывает дубликаты и нормализует пробелы. То есть
-- PutBucketPolicy → GetBucketPolicy перестал бы быть побайтовым, и ответ
-- отличался бы от отправленного клиентом.
--
-- Валидацию документа это не отменяет: её делает versitygw (auth.
-- ValidatePolicyDocument) ещё до вызова бэкенда — первая строка обязана
-- начинаться с '{', документ обязан парситься, Statement непустым, а каждый
-- principal существовать в IAM. Нам достаются уже проверенные байты.
--
-- Колонка остаётся NULL, когда политики нет: «нет политики» и «политика есть,
-- но пустая» — разные состояния, и первое должно отличаться от второго без
-- соглашения про пустую строку.
ALTER TABLE buckets ALTER COLUMN policy TYPE text USING policy::text;

-- +goose Down
-- Обратный ход требует, чтобы в policy лежал валидный JSON. Иначе не было бы
-- что раскатывать: до этого PR колонка была jsonb, а значит пустые значения —
-- NULL, и они же приходят за неимением политики.
ALTER TABLE buckets
  ALTER COLUMN policy TYPE jsonb USING NULLIF(b.policy, '')::jsonb;
