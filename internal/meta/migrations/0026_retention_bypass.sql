-- +goose Up
-- След обхода GOVERNANCE при удалении версии (ADR-0015, M6).
--
-- Версию под GOVERNANCE разрешено удалить досрочно — с заголовком обхода и
-- правом s3:BypassGovernanceRetention. До этой колонки такое удаление
-- переводило строку в 'deleting', а retain_until оставался в будущем, и
-- удалитель считал её заблокированной навсегда: клиент получил успешный ответ,
-- а байты лежали на ленте и в landing бессрочно, без единого сигнала об этом.
--
-- Отметка ставится в той же транзакции, что и переход в 'deleting', и означает
-- «удаление принято с обходом срока»: для помеченной строки срок GOVERNANCE
-- больше не блокировка. Юридический смысл у отметки именно про срок, поэтому
-- legal_hold и COMPLIANCE блокируют по-прежнему — обхода у них нет, и
-- поставить отметку для них нечем.
--
-- Снимать retain_until/retention_mode при обходе не стали: в строке обязан
-- остаться след, что удаление было досрочным и по какому сроку оно скучало.
--
-- Колонка nullable без DEFAULT: у строк, удалённых штатно, следа обхода нет,
-- и выдумывать его миграция не вправе.
ALTER TABLE objects ADD COLUMN retention_bypassed_at timestamptz;

COMMENT ON COLUMN objects.retention_bypassed_at IS
    'момент, когда удаление версии принято с обходом GOVERNANCE (ADR-0015); null — обхода не было';

-- +goose Down
ALTER TABLE objects DROP COLUMN IF EXISTS retention_bypassed_at;
