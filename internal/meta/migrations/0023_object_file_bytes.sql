-- Длина файла объекта на диске (участник пачки = файл целиком, ADR-0020).
--
-- Участник пачки — не только шифротекст, а весь файл landing: шифротекст +
-- зашифрованный манифест + футер (ADR-0019). В манифесте лежат соль частей
-- (из неё строится nonce каждого сегмента, #38), имя бакета и ключа, ETag и
-- пользовательские метаданные. В pax-заголовках участника (ADR-0020) их нет —
-- там только тенант, version_seq, обёрнутый DEK и версия KEK. Значит без
-- манифеста объект с ленты не расшифровать даже запасным проходом по tar, и
-- переносить в пачку надо весь файл.
--
-- Длину этого файла нельзя вывести формулой из БД: манифест — JSON переменной
-- длины (ключ, метаданные, таблица частей). Поэтому длина — отдельная колонка,
-- которую PUT и CompleteMultipart пишут в той же транзакции, что и строку
-- объекта. Загрузчик пачки объявляет длину участника из неё, а сборщик пачки
-- сверяет файл с ней в обе стороны (#63) — источник истины БД, файл проверяется.
--
-- Колонка nullable намеренно: длина известна только в момент записи файла,
-- задним числом по существующим строкам её не восстановить (файл на диске — не
-- SQL). Строка без file_bytes не архивируется: загрузчик отказывает явно,
-- вместо того чтобы угадать длину и обрезать манифест.
ALTER TABLE objects ADD COLUMN file_bytes bigint
  CHECK (file_bytes IS NULL OR file_bytes > 0);

