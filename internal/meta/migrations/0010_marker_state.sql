-- +goose Up
-- Маркер удаления — не «удалённая строка», а живая версия без данных. Пока он
-- лежал в state='deleted', из этого росли два дефекта:
--
--   1. выбор следующей текущей версии (`state NOT IN ('deleting','deleted')`)
--      никогда не видел маркер, и удаление текущей версии воскрешало объект,
--      спрятанный маркером под ней;
--   2. janitor (M6) чистит `deleted` старше meta.terminal_retention — то есть
--      все маркеры старше 90 дней исчезли бы молча, и похороненные под ними
--      версии воскресли бы массово.
--
-- Отдельное значение надёжнее, чем всюду помнить исключение
-- `is_delete_marker OR state NOT IN (...)`: такое исключение рано или поздно
-- забудут в новом запросе.
--
-- Значение добавляется ОТДЕЛЬНОЙ миграцией, потому что новое значение enum
-- нельзя использовать в той же транзакции, где оно добавлено, а goose
-- выполняет файл миграции в транзакции. Следующая миграция (0011) его
-- применяет. Ограничение проверено на деле:
--
--   ERROR: unsafe use of new value "marker" of enum type obj_state
--   HINT: New enum values must be committed before they can be used.
ALTER TYPE obj_state ADD VALUE IF NOT EXISTS 'marker';

