#!/usr/bin/env bash
# mutate.sh — безопасная мутация: сохранить, применить, проверить что применилось,
# прогнать тесты, восстановить.
#
# Правило «откат мутации — копированием файла, а не git checkout» в AGENTS.md не
# сработало дважды: правки до коммита в git нет, и `git checkout <файл>` стирает
# всю работу в этом файле. Механизм надёжнее правила.
#
# Использование:
#   ./hack/mutate.sh <файл> <выражение> <пакет> [шаблон теста]
# Пример:
#   ./hack/mutate.sh internal/meta/lock.go \
#       's/return ErrRetentionShorten/_ = 0/' ./internal/backend/ -run TestCompliance
#
# Три способа соврать «зелёным» встроены сюда, а не оставлены памяти исполнителя:
#
#   1. мутация обязана примениться — иначе «поймана» означает «ничего не меняли»;
#   2. базовый прогон обязан что-то выполнить — иначе пропущенные без DSN тесты
#      дают зелёный цвет, в котором ничего не проверяется;
#   3. для файлов миграций схема обязана пересоздаваться — иначе goose держит
#      уже применённую версию, и правка файла вообще не доходит до теста.
#
# Переменные окружения:
#
#   MODE=sed|perl   чем применять выражение. perl — для многострочных правок:
#                   sed одной строкой многрочный SQL не вырежет.
#                   Пример: MODE=perl EXPR='s/\s*AND kind = .data.\n//'
#   DROP_SCHEMA=<имя>  схема пересоздаётся перед базовым прогоном и перед
#                   прогоном после мутации. Нужно для мутаций *.sql. Имя
#                   обязано быть вида tapegw_test_<имя> — иначе отказ (rc=5):
#                   CASCADE с неверным именем удаляет чужие данные.
#
# Прогон мутации живёт в своей схеме: TAPEGW_TEST_SCHEMA_NS по умолчанию "mut",
# то есть пакет meta работает в tapegw_test_mut_meta, а не в общей
# tapegw_test_meta. Иначе мутация роняет схему из-под параллельного make check,
# который уже прогнал миграции и держит в ней строки.
#   PSQL=<команда>  чем ронять схему, по умолчанию psql.
set -euo pipefail

if [ "$#" -lt 3 ]; then
	echo "использование: $0 <файл> <выражение> <пакет> [-run шаблон]" >&2
	exit 2
fi

file=$1 expr=$2 pkg=$3
shift 3
testargs=("$@")

[ -f "$file" ] || { echo "нет файла $file" >&2; exit 1; }

# Прерванный в прошлом запуске (Ctrl-C, SIGKILL) trap не отработал, и файл
# остался изменённым: следующий прогон падает или висит по причине, которая
# выглядит как баг кода. Ищем свою копию и восстанавливаем её ДО всего
# остального — тогда прерванная мутация чинится тем же запуском.
#
# Две дыры, которые тут легко проглядеть:
#
#   * шаблон намеренно узкий: mktemp пишет ровно шесть символов после префикса,
#     а «mutate.*» подобрал бы и посторонний /tmp/mutate.py — и скопировал бы
#     его поверх целевого файла;
#   * копия привязана к имени файла (.name рядом с ней). Без привязки осколок от
#     pack.go восстановился бы поверх meta.go, и это уже не «вернуть как было»,
#     а порча другого файла.
for leftover in "$(ls -t "${TMPDIR:-/tmp}"/mutate-backup-?????? 2>/dev/null || true)"; do
	[ -f "$leftover" ] || continue
	stored=$(cat "$leftover.name" 2>/dev/null || true)
	if [ "$stored" != "$file" ]; then
		# Копия от другого файла: удалить молча нельзя (вдруг она от всё ещё
		# прерванной мутации), но и восстанавливать некуда.
		echo "КОПИЯ $leftover относится к '$stored', а не к '$file' — оставляем её в покое" >&2
		continue
	fi
	if ! diff -q "$leftover" "$file" >/dev/null 2>&1; then
		echo "НАЙДЕНА КОПИЯ ПРОШЛОГО ЗАПУСКА ($leftover), файл от неё отличается."
		echo "Восстанавливаю: похоже, прошлая мутация была прервана и осталась в рабочем дереве."
		cp "$leftover" "$file"
	fi
	rm -f "$leftover" "$leftover.name"
done

backup=$(mktemp "${TMPDIR:-/tmp}/mutate-backup-XXXXXX")
cp "$file" "$backup"
# Восстанавливаем из копии при любом выходе — по ошибке тестов, по Ctrl-C, по
# чему угодно. git checkout здесь не используется намеренно.
printf '%s' "$file" > "$backup.name"

restore() {
	cp "$backup" "$file"
	rm -f "$backup" "$backup.name"
	echo "--- восстановлено из копии ---"
}
trap restore EXIT INT TERM

# Своя схема у мутаций по умолчанию: см. комментарий выше. Обычный прогон её не
# видит, его схемы остаются нетронутыми.
export TAPEGW_TEST_SCHEMA_NS="${TAPEGW_TEST_SCHEMA_NS:-mut}"

drop_schema() {
	[ -n "${DROP_SCHEMA:-}" ] || return 0
	# Скрипт роняет схемы с CASCADE, значит защищаться от неверного имени он
	# обязан сам, а не полагаться на внимательность запускающего: опечатка
	# DROP_SCHEMA=tapegw при DSN на рабочий стенд (тот же Postgres, где живут
	# Phobos DSS и e2e-данные) снесла бы основную схему со всем содержимым.
	# Проходить могут только схемы, которые создаёт testdb.
	if [[ ! "$DROP_SCHEMA" =~ ^tapegw_test_[a-z0-9_]+$ ]]; then
		echo "DROP_SCHEMA='$DROP_SCHEMA' не похоже на тестовую схему: разрешены только вида tapegw_test_<имя> " >&2
		echo "(те, что создаёт testdb). Разыменование идёт в CASCADE, и ошибиться здесь — значит удалить чужие данные." >&2
		exit 5
	fi
	if [ -z "${TAPEGW_TEST_DSN:-}" ]; then
		echo "DROP_SCHEMA задан, а TAPEGW_TEST_DSN нет: схема не пересоздана, и мутация миграции ничего не проверит" >&2
		exit 4
	fi
	# Имя — идентификатор, в двойных кавычках: без них оно подставлялось в SQL
	# как есть.
	${PSQL:-psql} "$TAPEGW_TEST_DSN" -qc \
		"DROP SCHEMA IF EXISTS \"$DROP_SCHEMA\" CASCADE" >/dev/null
}

apply_mutation() {
	case "${MODE:-sed}" in
	perl) perl -0777 -pi -e "$expr" "$file" ;;
	sed) sed -i "$expr" "$file" ;;
	*) echo "MODE бывает sed или perl, а не $MODE" >&2; exit 2 ;;
	esac
}

# Вторая ложная зелёность, которую я поймал на себе: тесты, которым нужен
# Postgres, при незаданном TAPEGW_TEST_DSN не падают, а пропускаются. Прогон
# зелёный, «мутация не поймана» — хотя не проверялось вообще ничего. Поэтому
# сначала базовый прогон ДО мутации: после неё падение от отсутствия БД
# выглядело бы как «мутация поймана».
drop_schema
base=$(go test -count=1 -v "$pkg" "${testargs[@]:-}" 2>&1 || true)
if ! grep -qE '^(--- PASS|--- FAIL)' <<<"$base"; then
	skipped=$(grep -cE '^--- SKIP' <<<"$base" || true)
	echo "БАЗОВЫЙ ПРОГОН НИЧЕГО НЕ ВЫПОЛНИЛ в $pkg (пропущено: ${skipped:-0})"
	echo "Пропущенный тест — не проверка: при незаданном TAPEGW_TEST_DSN тесты на Postgres не падают, а пропускаются, и прогон выглядит зелёным. Задайте DSN или поправьте шаблон теста." >&2
	exit 4
fi
if grep -qE '^--- FAIL' <<<"$base"; then
	echo "БАЗОВЫЙ ПРОГОН КРАСНЫЙ до всякой мутации — сначала почините тесты." >&2
	exit 4
fi

apply_mutation

if diff -q "$backup" "$file" >/dev/null; then
	# Самая частая ложная зелёность: мутация не применилась (опечатка в
	# выражении, код уже изменился), тесты прошли — и в отчёте «мутация
	# поймана», хотя ничего не проверялось.
	echo "МУТАЦИЯ НЕ ПРИМЕНИЛАСЬ: $expr ничего не изменило в $file" >&2
	exit 3
fi

echo "### мутация применена: $expr"
drop_schema
if go test -count=1 "$pkg" "${testargs[@]:-}"; then
	echo "ВНИМАНИЕ: тесты прошли несмотря на мутацию — проверка ничего не ловит" >&2
	exit 1
fi
echo "### мутация поймана (тесты упали, как и должно)"
