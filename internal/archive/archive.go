package archive

// Интерфейс к архиву объектов (лентам Phobos).
//
// Он здесь по одной причине: правило 2 требует, чтобы `go build ./...` и
// `go test ./...` проходили без Phobos и без cgo. Если бы rebuild-meta обращался
// к libphobos напрямую, его главный тест — «список объектов взят из архива, а не
// из нашей БД» — нельзя было бы запустить в CI вообще, и проверка превратилась бы
// в чтение собственной базы. Поэтому восстановление описано интерфейсом, а
// cgo-реализация живёт под тегом `phobos` в стенде ci-dir.
//
// Второй причины меньше, но она приятнее: фейк — это каталог на диске, и на нём
// можно собрать лживый архив (объект без манифеста, манифест не под тем DEK,
// объект удалённого тенанта) без ленты и без драйверов.
//
// Читаем мы только ХВОСТ объекта. Метаданные версии целиком лежат в манифесте
// перед 48-байтным футером (ADR-0019), а сами данные при восстановлении БД не
// нужны вовсе — они и так на ленте, их никто не переносил.

import (
	"context"
)

// ObjectRef — объект архива: идентификатор и атрибуты.
type ObjectRef struct {
	// Oid — идентификатор объекта в архиве. Для Phobos это UUID версии объекта:
	// mover кладёт его же в атрибут tapegw.version.
	Oid string
	// Attrs — атрибуты, как их отдаёт архив. Разбирает ParseAttributes.
	Attrs map[string]string
}

// Archive — чтение архива. Реализация поверх Phobos обязана быть безопасной для
// вызова без открытой транзакции Postgres (правило 13).
type Archive interface {
	// List — все объекты архива с атрибутами. Именно этот список — источник
	// истины при восстановлении: если rebuild-meta возьмёт его из БД, тест
	// «восстановили из лент» ничего не проверяет.
	List(ctx context.Context) ([]ObjectRef, error)

	// Size — размер объекта в байтах.
	Size(ctx context.Context, oid string) (int64, error)

	// ReadAt — чтение произвольного куска объекта. Чтение хвоста не требует
	// перемотки к началу, и реализация не обязана читать данные целиком.
	ReadAt(ctx context.Context, oid string, p []byte, off int64) (int, error)
}
