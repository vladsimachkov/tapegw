-- Когда версия KEK перестала быть активной (ADR-0014).
--
-- Ротация KEK переоборачивает TEK, но старую версию KEK нельзя выбросить в тот
-- же момент: на неё до сих пор ссылаются экспорты ключей и дампы БД, сделанные
-- до ротации. Забыть её раньше времени — значит сделать эти копии нечитаемыми, а
-- «забыть позже, чем нужно» — значит держать ключ дольше обещанного срока. И то и
-- другое считается от момента, когда версия уступила активной, и нигде раньше
-- этот момент не записывался: файл кольца KEK хранит версию → ключ, без дат.
--
-- superseded_at IS NULL означает «ещё активна ИЛИ когда устарела — неизвестно».
-- Оба случая для отказа от версии недоказуемы, поэтому CLI для них отказывает:
-- недоказуемое «срок прошёл» опаснее, чем «подождите».

CREATE TABLE kek_versions (
  version       int PRIMARY KEY,
  created_at    timestamptz NOT NULL DEFAULT now(),
  superseded_at timestamptz
);

-- Версии, на которые уже есть ссылки, заводим сразу. Иначе первая ротация
-- поставит superseded_at только новой активной версии, а про старую забудет — и
-- «когда же её можно выбросить» снова станет вопросом к памяти оператора.
--
-- Отмечаются они с superseded_at = NULL: когда именно версия уступила, из БД не
-- следует, а угадывать «вот сейчас» значило бы задним числом открыть срок,
-- который мог уже пройти.
INSERT INTO kek_versions (version)
SELECT DISTINCT kek_version FROM tenants WHERE wrapped_key IS NOT NULL
UNION
SELECT DISTINCT kek_version FROM accounts
ON CONFLICT (version) DO NOTHING;

