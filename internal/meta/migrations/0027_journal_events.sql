-- +goose Up
-- Журнал метаданных: события (ADR-0023, план «Журнал метаданных на ленте»).
--
-- Манифест описывает версию в момент её записи и больше не меняется, а
-- метаданные после записи правятся: продлевают retention, ставят и снимают
-- legal hold, ставят маркеры удаления, удаляют версии по versionId, меняют
-- конфигурацию бакета. Без журнала `rebuild-meta` после аварии вернёт
-- состояние, которого не было: продленный COMPLIANCE снова станет удаляемым по
-- старому сроку, а ключ из-под маркера — живым.
--
-- Событие записывается **в той же транзакции, что и изменение** (ADR-0023,
-- п. 1). Отдельный шаг после коммита дал бы окно, в котором изменение есть, а
-- события нет, и падение в этом окне потеряло бы блокировку молча. Поэтому
-- здесь только таблица, а вся выдача номера и вставка — внутри транзакции
-- изменения (meta.appendEvent).
--
-- Порядок внутри тенанта задаёт tenants.journal_seq, а не sequence Postgres:
-- последовательность не откатывается вместе с транзакцией, и откатившаяся
-- операция оставила бы дырку в нумерации — а дырка в журнале означает
-- «потерянное событие» и обязана быть алертом. Счётчик на строке тенанта
-- откатывается вместе с изменением, поэтому нумерация плотная по построению.
--
-- Таблица только на добавление — тем же триггером, что media_events (0018):
-- событие журнала не исправляют задним числом. Сегменты журнала (следующий
-- шаг плана) описываются **диапазоном** seq_first..seq_last, а не ссылкой
-- события на сегмент, поэтому UPDATE событиям не нужен вовсе и ограничение
-- ничего не обходят.
--
-- object_id и bucket_id намеренно без внешних ключей. Событие обязано пережить
-- строку, о которой оно: janitor (M6) физически убирает версии из 'deleted' по
-- meta.terminal_retention, и FK либо отверг бы чистку, либо каскадом стёр бы
-- журнал вместе с данными. Имена в payload — тоже намеренно: бакет после
-- восстановления получает другой id, и сопоставить событие бакету можно только
-- по имени. Открытым в payload при этом не остаётся ничего лишнего — таблица
-- живёт в Postgres, а на ленту пойдёт зашифрованный сегмент (ADR-0020 §3).

CREATE TYPE journal_event_kind AS ENUM (
    -- retention версии изменён (PutObjectRetention).
    'retention',
    -- legal hold включён или снят (PutObjectLegalHold).
    'legal_hold',
    -- маркер удаления создан или убран (DeleteObject без versionId,
    -- удаление маркера по versionId).
    'delete_marker',
    -- версия ушла в 'deleting' — по versionId, при перезаписи null-версии,
    -- с обходом GOVERNANCE или без.
    'delete_version',
    -- снимок конфигурации бакета после изменения (версионирование, Object
    -- Lock, срок по умолчанию, владелец, ACL, политика, удаление бакета).
    'bucket_config'
);

-- Счётчик порядка событий внутри тенанта. Не sequence: см. комментарий выше.
-- Выдаётся единственным UPDATE под блокировкой строки тенанта в транзакции
-- изменения (ADR-0023 п. 2), поэтому всегда равен номеру последнего события.
ALTER TABLE tenants ADD COLUMN journal_seq bigint NOT NULL DEFAULT 0;

COMMENT ON COLUMN tenants.journal_seq IS
    'номер последнего события журнала тенанта; выдаётся под блокировкой строки в транзакции изменения (ADR-0023)';

CREATE TABLE journal_events (
  -- Тенант берётся из строки (бакета или версии), а не из учётки запроса: под
  -- обходом по роли страж отдаёт «все тенанты», и событие уехало бы в
  -- несуществующий тенант (находка PR #127 в той же форме).
  tenant_id   bigint NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  journal_seq bigint NOT NULL CHECK (journal_seq > 0),
  kind        journal_event_kind NOT NULL,
  -- Версия, к которой относится событие. У снимка конфигурации бакета версии
  -- нет — отсюда CHECK ниже.
  object_id   uuid,
  bucket_id   bigint NOT NULL,
  payload     jsonb NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  -- Номер уникален внутри тенанта и плотный: по этому ключу rebuild-meta
  -- применяет события по порядку и видит пропуск.
  PRIMARY KEY (tenant_id, journal_seq),
  -- Форму «снимок бакета без версии, всё остальное с версией» держим в схеме:
  -- перепутать поля в вызове легче, чем кажется, а молча записанное событие не
  -- разберётся при восстановлении.
  CHECK ((kind = 'bucket_config') = (object_id IS NULL))
);

-- Отдельного индекса под чтение «события тенанта по порядку» нет: PRIMARY KEY
-- он покрывает ровно тем же составным ключом.

CREATE TRIGGER journal_events_append_only
  BEFORE UPDATE OR DELETE ON journal_events
  FOR EACH ROW EXECUTE FUNCTION tapegw_journal_append_only();

