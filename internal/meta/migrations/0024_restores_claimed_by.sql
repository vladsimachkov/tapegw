-- +goose Up
-- Идентичность воркера, держящего строку restore (узел/слот — та же схема,
-- что у packs.claimed_by из #74).
--
-- Чтение пачки с ленты — ожидание свободного драйва, монтирование,
-- позиционирование и передача гигабайт: минуты, а то и десятки минут
-- (ADR-0021). Lease в next_try_at, выставленный один раз при захвате, истёк
-- бы посреди чтения, и второй воркер забрал бы те же строки: та же пачка
-- читается с ленты второй раз (драйв отнят у других задач), attempts растёт
-- на каждом перехвате, и медленное — не сломанное — восстановление
-- доходит до failed с причиной «захват истёк».
--
-- Поэтому продление (раз в треть срока) обязано отличать владельца: короткий
-- UPDATE ... WHERE claimed_by = me вне транзакции чтения (правило 13), а
-- переходы restored/failure/corrupt проверяют, что их вызывает текущий
-- владелец. Без колонки-владельца продление не отличить от чужого захвата.
ALTER TABLE restores ADD COLUMN claimed_by text;

-- +goose Down
ALTER TABLE restores DROP COLUMN IF EXISTS claimed_by;
