-- +goose Up
-- T2 PR#3a: манифест в конце файла объекта (ADR-0019).
--
-- Сама миграция ничего в схему не добавляет, и это не забывчивость: манифест
-- лежит в файле объекта, а не в Postgres, и выводится из уже сохранённых
-- размеров и солей частей. Колонка «манифест есть» означала бы вторую версию
-- правды о том, что лежит в файле, и при первом же расхождении она начала бы
-- противоречить самому файлу.
--
-- Проверить здесь нужно другое: что ни одна версия не была записана до появления
-- манифеста. Файлы прежнего формата не имеют ни шифротекста манифеста, ни
-- футера, и rebuild-meta (PR#3b) споткнётся о них молча — «файл есть, ключ есть,
-- а восстановить нельзя». Поэтому миграция отказывается применяться и называет
-- причину, а не оставляет базу в состоянии «частично восстановимо».
--
-- Проверка делается на таблице с данными (правило 11): на пустой схеме шаг
-- выглядит точно так же, но не гарантирует ничего.

-- +goose StatementBegin
DO $$
DECLARE n bigint;
BEGIN
  SELECT count(*) INTO n FROM objects WHERE NOT is_delete_marker;
  IF n > 0 THEN
    RAISE EXCEPTION
      'в objects % версий, записанных до появления манифеста (ADR-0019): '
      'в их файлах нет ни шифротекста манифеста, ни футера, и rebuild-meta их '
      'не восстановит. На ленту ничего не записано (M4 не сделан) — удаляет их '
      'человек вместе со стендом', n;
  END IF;
END $$;
-- +goose StatementEnd

