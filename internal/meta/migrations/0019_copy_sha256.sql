-- +goose Up
-- Ожидаемая контрольная сумма содержимого копии (Ф0.4 из предложения 0014,
-- поправка ревьюера к ADR-0021).
--
-- Нужна она не «для порядка», а потому что локальная передача (from_op) на
-- операцию get обязана сверять **ожидаемую** сумму, а не посчитанную при
-- чтении. Если сверять посчитанную, проверка замкнута сама на себя: испорченное
-- чтение с ленты даёт «правильную» сумму испорченных данных, повреждение
-- записывается новой копией как проверенное, а копия-источник по Р10 становится
-- мёртвой. Повреждение тихо размножится и вытеснит единственный оригинал.
--
-- Сумма одинакова у всех копий одного объекта (это сумма потока Phobos), но
-- держится у копии: проверять её проще именно там, где она нужна, а не ходить за
-- ней к пачке или объекту.
--
-- Обязательна для 'done': копия, которая не может сказать, что именно лежит в
-- оригинале, не годится в источник копии или repack.

ALTER TABLE archive_copies
  ADD COLUMN sha256 bytea;

-- Размер обязана быть 32 байта: bytea принимает что угодно, и сумма длиной 20
-- байтов прошла бы как «есть», а сверять её было бы нечем.
ALTER TABLE archive_copies
  ADD CONSTRAINT archive_copies_sha256_len
  CHECK (sha256 IS NULL OR octet_length(sha256) = 32);

ALTER TABLE archive_copies
  ADD CONSTRAINT archive_copies_done_has_sha256
  CHECK (state <> 'done' OR sha256 IS NOT NULL);

-- +goose Down
ALTER TABLE archive_copies
  DROP CONSTRAINT archive_copies_done_has_sha256,
  DROP CONSTRAINT archive_copies_sha256_len,
  DROP COLUMN sha256;
