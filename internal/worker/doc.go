// Package worker — фоновые воркеры: migrator, recaller, janitor, deleter.
//
// Появляются на M4 (migrator), M5 (recaller), M4/M6 (janitor), M6 (deleter).
// Общие требования, одинаковые для всех четырёх:
//
//   - выборка работы: SELECT ... FOR UPDATE SKIP LOCKED с лимитом по числу
//     объектов, по байтам и по таймеру;
//   - переход состояния: UPDATE ... WHERE state = <ожидаемое>. Ноль затронутых
//     строк — «опередили», молча пропускаем;
//   - идемпотентность: повтор после падения в любой точке даёт тот же результат.
//     Для каждого шага обязателен тест «упасть после шага N» на fake.Store;
//   - ретраи: attempts+1, экспоненциальный next_try_at, после max_attempts —
//     состояние failed и алерт;
//   - вызовы Phobos только из пула phobos.max_inflight; migrator и recaller
//     получают отдельные пулы, чтобы restore не ждал архивацию;
//   - отмена ctx не прерывает идущий C-вызов: при остановке воркер дожидается
//     текущего батча.
