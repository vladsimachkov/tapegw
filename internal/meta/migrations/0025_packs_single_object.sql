-- Крупный объект проходит ту же машину состояний, что пачка (ARCHITECTURE, M4
-- «крупные объекты»): строка пачки несёт захват, запечатывание и копии, но
-- байты на ленту идут сырым файлом объекта (ADR-0020 §1), а не tar-пачкой.
--
-- Признак обязан быть явным: продолжение запечатанной единицы (ResumePacks)
-- по нему выбирает, какие байты пересобирать. Косвенный признак — «один
-- участник и total_bytes равны pack_length» — молча принимает пачку из одного
-- мелкого участника за крупный объект: у настоящей пачки total_bytes больше
-- суммы участников ровно на заголовки tar, индекс и футер, и это различие
-- нигде не зафиксировано как ограничение.
--
-- Значение по умолчанию false: все пачки, записанные до колонки, — пачки.
ALTER TABLE packs ADD COLUMN single_object boolean NOT NULL DEFAULT false;

-- +goose Down
ALTER TABLE packs DROP COLUMN IF EXISTS single_object;
