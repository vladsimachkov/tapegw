package meta

// Идентификаторы базовых строк, созданных миграцией 0005.
//
// Колонки tenant_id и pool_id сделаны NOT NULL **без DEFAULT** именно для того,
// чтобы любой путь кода, который забыл указать тенанта или пул, падал с ошибкой
// NOT NULL на первом же тесте, а не молча писал данные в первый тенант.
// Поэтому здесь нет «достать откуда-то по умолчанию» — значение передаётся явно.
//
// Оба — заглушка однотенантовой установки. Этап T1 (ADR-0009) заменяет их на
// настоящего тенанта из контекста запроса; grep по DefaultTenantID показывает
// все места, которые нужно поправить.
const (
	// DefaultTenantID — тенант `default` из миграции 0005.
	DefaultTenantID int64 = 1
	// DefaultPoolID — общий пул `shared` из миграции 0005. По ADR-0013 каждая
	// запись обязана нести тег пула, поэтому пул указывается даже в
	// однотенантовой установке, а не оставляется «без пула».
	DefaultPoolID int64 = 1
)
